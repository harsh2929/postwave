/**
 * Config plugin: stop the app target autolinking the private SwiftUICore.
 *
 * WHY. `ios/Moosewave/PostwaveAppIntents.swift` imports AppIntents. On the
 * iOS 26 SDK, AppIntents' swiftinterface transitively references SwiftUI, and
 * SwiftUI's implementation now lives in SwiftUICore.framework — which is
 * private. The Swift compiler therefore emits an autolink directive for it and
 * the linker refuses the whole app:
 *
 *   Undefined symbols for architecture arm64:
 *     Could not parse or use implicit file '…/SwiftUICore.framework/SwiftUICore.tbd':
 *     cannot link directly with 'SwiftUICore' because product being built is
 *     not an allowed client of it
 *
 * Apps are allowed to link SwiftUI, never SwiftUICore. Suppressing just that
 * one autolink is the narrow fix — SwiftUI itself still links normally, and no
 * behaviour changes.
 *
 * WHY THIS IS A PLUGIN AND NOT AN EDIT TO ios/Podfile. `ios/` is gitignored
 * and regenerated by `expo prebuild`, so a Podfile edit survives exactly until
 * the next prebuild and then the build breaks again for the next person.
 *
 * WHY IT IS SCOPED TO Pods-Moosewave. Applied globally — e.g. as an
 * xcodebuild-wide `OTHER_SWIFT_FLAGS` override — the value gets re-parsed by
 * other pods and the bare word `SwiftUICore` is taken as an input FILE, which
 * fails the Sentry target with:
 *   error: unexpected input file: …/ios/Pods/SwiftUICore
 *
 * REMOVE THIS when the toolchain stops emitting the autolink (a future Xcode,
 * or an Expo/React Native release that carries its own fix). The marker below
 * makes it greppable.
 */
const { withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const MARKER = "postwave:swiftuicore-autolink-fix";

const HOOK = `
    # ${MARKER}
    # See plugins/withSwiftUICoreAutolinkFix.js for the full reasoning.
    installer.pods_project.targets.each do |target|
      next unless target.name == 'Pods-Moosewave'
      target.build_configurations.each do |bc|
        flags = bc.build_settings['OTHER_SWIFT_FLAGS'] || '$(inherited)'
        flags = flags.join(' ') if flags.is_a?(Array)
        unless flags.include?('-disable-autolink-framework SwiftUICore')
          bc.build_settings['OTHER_SWIFT_FLAGS'] =
            "#{flags} -disable-autolink-framework SwiftUICore"
        end
      end
    end
`;

module.exports = function withSwiftUICoreAutolinkFix(config) {
  return withDangerousMod(config, [
    "ios",
    (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, "Podfile");
      if (!fs.existsSync(podfile)) {
        // Nothing to patch yet; a later prebuild will run this again.
        return cfg;
      }
      const source = fs.readFileSync(podfile, "utf8");
      if (source.includes(MARKER)) return cfg;

      // Anchor on react_native_post_install's closing paren inside post_install.
      const anchor = /(\n\s*post_install do \|installer\|[\s\S]*?\n\s*\)\n)/;
      if (!anchor.test(source)) {
        throw new Error(
          "[withSwiftUICoreAutolinkFix] could not find the post_install hook in " +
            "ios/Podfile. The Expo template changed shape — re-anchor this plugin " +
            "rather than dropping it, or the app target will fail to link against " +
            "the iOS 26 SDK.",
        );
      }
      fs.writeFileSync(podfile, source.replace(anchor, `$1${HOOK}`), "utf8");
      return cfg;
    },
  ]);
};
