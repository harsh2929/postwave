/**
 * Config plugin: the ANDROID half of "share a link into Moosewave" (NATIVE#23).
 *
 * WHY A PLUGIN AND NOT app.json. `android.intentFilters` in app.json only ever
 * decorates MainActivity, and that is not enough here. An `ACTION_SEND` intent
 * carries its payload in `Intent.EXTRA_TEXT`, while React Native's `Linking`
 * surface exposes only `getIntent().getData()` — which is null for a share.
 * A manifest-only "fix" would put Moosewave in the Android share sheet and then
 * open it on whatever screen was last shown, which is worse than being absent.
 *
 * WHAT THIS ADDS. One small, isolated activity that never touches MainActivity:
 *
 *   Android share sheet
 *     -> PostwaveShareActivity   (no UI, finishes immediately)
 *        -> canonicalises the shared text against the SAME policy as the iOS
 *           extension (targets/share/index.swift): one Moosewave entity link or
 *           one bare email address, nothing else
 *        -> re-emits it as a `moosewave://` VIEW intent aimed at this package
 *     -> MainActivity -> Linking "url" event -> useDeepLinkRouting
 *
 * So the shared item re-enters through the deep-link parser that is already
 * built and tested (lib/deepLinks.ts + lib/navDeepLinks.ts) instead of through
 * a second, unvetted ingestion path. NOTHING is persisted: unlike iOS — where
 * the extension is a separate process and must hand over through the App Group
 * — Android can forward the intent in-process, so there is no queue, no TTL and
 * no stored copy of anything the user shared.
 *
 * The two functions the behaviour actually lives in are exported and unit
 * tested in src/lib/androidShareTarget.test.ts; this file is only the wiring.
 */
const {
  withAndroidManifest,
  withDangerousMod,
} = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

/** Relative to the application package, matching the `.Name` manifest form. */
const SHARE_ACTIVITY_CLASS = "PostwaveShareActivity";
const SHARE_ACTIVITY_NAME = `.${SHARE_ACTIVITY_CLASS}`;

/**
 * The `<activity>` node, in the xml2js shape `withAndroidManifest` hands over.
 *
 * `exported` must be true — the share sheet is another process. Everything else
 * is containment: `noHistory` + `excludeFromRecents` keep a shared link out of
 * the recents list (where a screenshot of the task switcher would show it), and
 * `Theme.NoDisplay` means no frame is ever drawn.
 */
function shareActivityNode() {
  return {
    $: {
      "android:name": SHARE_ACTIVITY_NAME,
      "android:exported": "true",
      "android:excludeFromRecents": "true",
      "android:noHistory": "true",
      "android:taskAffinity": "",
      "android:theme": "@android:style/Theme.NoDisplay",
      "android:label": "Moosewave",
    },
    "intent-filter": [
      {
        action: [{ $: { "android:name": "android.intent.action.SEND" } }],
        category: [
          { $: { "android:name": "android.intent.category.DEFAULT" } },
        ],
        // text/plain only. Moosewave has no action for an image or a file, and
        // claiming a MIME type the app cannot use is how an app earns a
        // permanent place in a share sheet it never satisfies.
        data: [{ $: { "android:mimeType": "text/plain" } }],
      },
    ],
  };
}

/**
 * Add the share activity to a parsed AndroidManifest. Pure and idempotent —
 * `expo prebuild` runs mods repeatedly, and a duplicated `<activity>` is a
 * manifest-merger failure, not a warning.
 */
function addShareTargetActivity(androidManifest) {
  const application = androidManifest?.manifest?.application?.[0];
  if (!application) {
    throw new Error(
      "[withAndroidShareTarget] AndroidManifest has no <application> node",
    );
  }
  const activities = application.activity ?? [];
  const already = activities.some(
    (activity) => activity?.$?.["android:name"] === SHARE_ACTIVITY_NAME,
  );
  if (!already) activities.push(shareActivityNode());
  application.activity = activities;
  return androidManifest;
}

/**
 * The activity source.
 *
 * Deliberately string-based rather than `Uri`-based: `Uri.parse` never throws
 * and quietly accepts a great deal, and the point of this file is to accept
 * exactly two shapes. The literals below are pinned against the iOS extension
 * and the shared route registry by androidShareTarget.test.ts.
 */
function renderShareActivityKotlin(packageName) {
  if (!/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/.test(packageName)) {
    throw new Error(
      `[withAndroidShareTarget] refusing to emit sources for an implausible package name: ${packageName}`,
    );
  }
  return `package ${packageName}

// GENERATED by plugins/withAndroidShareTarget.js — do not edit in android/.
//
// Receives an ACTION_SEND text/plain intent, keeps it ONLY if it is a canonical
// Moosewave entity link or a single bare email address, and re-emits it as a
// moosewave:// VIEW intent so the app's existing deep-link parser handles it.
// Nothing is stored and nothing is logged; a rejected share finishes silently
// because the user already sees the share sheet dismiss.

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

private const val MAX_SHARED_CHARS = 2048

// Mirrors ENTITIES in packages/route-map/src/entities.ts, filtered to entities
// whose \`surfaces.mobile\` is not "none". This activity queues a URL for the app
// to open, so accepting an entity the app has no screen for would consume the
// share and strand the user — which is why \`affiliates\` and
// \`sequence-templates\` are absent.
// apps/mobile/src/lib/androidShareTarget.test.ts fails if these drift.
private val SLUG_TO_ACTION = mapOf(
    "approvals" to "approval",
    "subscribers" to "subscriber",
    "campaigns" to "campaign",
    "sequences" to "sequence",
    "forms" to "form",
    "lists" to "list",
    "segments" to "segment",
    "helpdesk" to "helpdesk-conversation",
    "templates" to "template",
    "migrations" to "migration",
    "discounts" to "discount",
    "integrations" to "integration",
    "flows" to "flow",
    "inbound-webhooks" to "inbound-webhook",
    "landing-pages" to "landing-page",
    // Mobile ships app/(tabs)/suppressions/[email].tsx, so this opens a real
    // screen rather than consuming the share and stranding the user.
    "suppressions" to "suppression"
)
private val ENTITY_ACTIONS = SLUG_TO_ACTION.values.toSet()

// Mirrors isSafeResourceId in packages/route-map/src/entities.ts.
private val SAFE_ID = Regex("^[A-Za-z0-9_-]{1,128}$")
private val CANONICAL_UUID = Regex("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
private val EMAIL = Regex("^[^\\\\s@]{1,64}@[^\\\\s@]{1,255}\\\\.[^\\\\s@]{2,63}$")

private fun isEntityID(action: String, id: String): Boolean {
    if (!SAFE_ID.matches(id)) return false
    return action != "helpdesk-conversation" || CANONICAL_UUID.matches(id)
}

internal fun entityShareTarget(value: String): String? {
    if (value.startsWith("moosewave://")) {
        val parts = value.removePrefix("moosewave://").split("/")
        if (parts.size != 2) return null
        val action = parts[0].lowercase()
        if (!ENTITY_ACTIONS.contains(action) || !isEntityID(action, parts[1])) return null
        return "moosewave://" + action + "/" + parts[1]
    }
    if (value.startsWith("https://app.moosewave.com/")) {
        val parts = value.removePrefix("https://app.moosewave.com/").split("/")
        if (parts.size != 3 || parts[0] != "app") return null
        val action = SLUG_TO_ACTION[parts[1].lowercase()]
        if (action == null || !isEntityID(action, parts[2])) return null
        // Always re-emitted as the custom scheme: an https:// hand-off would
        // depend on Android App Links verification having succeeded on this
        // device, and an unverified link opens the browser instead.
        return "moosewave://" + action + "/" + parts[2]
    }
    return null
}

internal fun canonicalShareTarget(raw: String?): String? {
    val trimmed = raw?.trim() ?: return null
    if (trimmed.isEmpty() || trimmed.length > MAX_SHARED_CHARS) return null
    val withoutQuery = trimmed.substringBefore('?').substringBefore('#')
    val entity = entityShareTarget(withoutQuery)
    if (entity != null) return entity
    if (EMAIL.matches(trimmed)) {
        return "moosewave://subscribers?q=" + Uri.encode(trimmed)
    }
    // Arbitrary text and generic URLs are not Moosewave actions. Same rule the
    // iOS extension applies in targets/share/index.swift.
    return null
}

class ${SHARE_ACTIVITY_CLASS} : Activity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        // getCharSequenceExtra, NOT getStringExtra.
        //
        // EXTRA_TEXT is declared as a CharSequence, and the common producers put
        // a Spanned in it — ShareCompat.IntentBuilder.setText() and Chrome's
        // "Share link" both do. getStringExtra returns null for a Spanned rather
        // than converting it, so the share dismissed silently with no error for
        // exactly the senders this feature exists to receive from. A plain
        // String still arrives here unchanged; CharSequence is the wider type.
        val shared = intent?.getCharSequenceExtra(Intent.EXTRA_TEXT)?.toString()
        val target = canonicalShareTarget(shared)
        if (target != null) {
            val view = Intent(Intent.ACTION_VIEW, Uri.parse(target))
            view.setPackage(packageName)
            view.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
            startActivity(view)
        }
        finish()
    }
}
`;
}

function withShareActivitySource(config) {
  return withDangerousMod(config, [
    "android",
    async (cfg) => {
      const packageName = cfg.android?.package;
      if (!packageName) {
        throw new Error(
          "[withAndroidShareTarget] android.package is required to emit the share activity",
        );
      }
      const destDir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "java",
        ...packageName.split("."),
      );
      fs.mkdirSync(destDir, { recursive: true });
      fs.writeFileSync(
        path.join(destDir, `${SHARE_ACTIVITY_CLASS}.kt`),
        renderShareActivityKotlin(packageName),
        "utf8",
      );
      return cfg;
    },
  ]);
}

function withAndroidShareTarget(config) {
  const withSource = withShareActivitySource(config);
  return withAndroidManifest(withSource, (cfg) => {
    cfg.modResults = addShareTargetActivity(cfg.modResults);
    return cfg;
  });
}

module.exports = withAndroidShareTarget;
module.exports.addShareTargetActivity = addShareTargetActivity;
module.exports.renderShareActivityKotlin = renderShareActivityKotlin;
module.exports.shareActivityNode = shareActivityNode;
module.exports.SHARE_ACTIVITY_CLASS = SHARE_ACTIVITY_CLASS;
module.exports.SHARE_ACTIVITY_NAME = SHARE_ACTIVITY_NAME;
