/**
 * api/aiRegressionAdmin.ts — the admin half of the AI regression harness.
 *
 *   GET  /api/v1/ai-regression/settings         admin
 *   PUT  /api/v1/ai-regression/settings         admin
 *   POST /api/v1/ai-regression/runs             admin → 202 {run_id,status,runtime}
 *   POST /api/v1/ai-regression/golden-examples  admin → 201 GoldenExample
 *
 * Mounted at apps/api/internal/ai_regression/handlers.go:65-76; the roles are
 * the ones routeauth/manifest.json records for each path.
 *
 * Payloads come back as `unknown` on purpose: lib/aiRegressionAdmin owns every
 * shape decision so the parsing is provable in node.
 */
import { rawRequest, type AIApiResult } from "./request";

/** GET /api/v1/ai-regression/settings — a full settings object, always. */
export async function fetchRegressionSettings(): Promise<AIApiResult<unknown>> {
  return rawRequest<unknown>("GET", "/api/v1/ai-regression/settings");
}

/**
 * PUT /api/v1/ai-regression/settings — a WHOLE-OBJECT replace. The handler
 * decodes into a fresh RegressionSettings and PutSettings writes all four
 * fields, so an omitted key is written as its zero value, not left alone.
 */
export async function putRegressionSettings(body: {
  warn_threshold: number;
  hard_gate_enabled: boolean;
  hard_gate_threshold: number;
  min_examples_for_gate: number;
}): Promise<AIApiResult<unknown>> {
  return rawRequest<unknown>("PUT", "/api/v1/ai-regression/settings", body);
}

/** POST /api/v1/ai-regression/runs — 202 Accepted; the run executes server-side. */
export async function triggerRegressionRun(body: {
  model_version_tag: string;
}): Promise<AIApiResult<unknown>> {
  return rawRequest<unknown>("POST", "/api/v1/ai-regression/runs", body);
}

/**
 * POST /api/v1/ai-regression/golden-examples — a manual reference.
 *
 * request_id is part of the BODY (a lowercase UUID the handler validates
 * before anything else), not an idempotency header; it is generated by the
 * caller and carried through unchanged.
 */
export async function captureGoldenExample(body: {
  surface_kind: string;
  brief: string;
  approved_output: string;
  request_id: string;
}): Promise<AIApiResult<unknown>> {
  return rawRequest<unknown>(
    "POST",
    "/api/v1/ai-regression/golden-examples",
    body,
  );
}
