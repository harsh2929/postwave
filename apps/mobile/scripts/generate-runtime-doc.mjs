#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDir, "..");
const outputPath = join(appRoot, "runtime-config.generated.md");
const packageJson = JSON.parse(readFileSync(join(appRoot, "package.json")));
const appJson = JSON.parse(readFileSync(join(appRoot, "app.json")));
const eas = JSON.parse(readFileSync(join(appRoot, "eas.json")));
const expo = appJson.expo ?? {};

function dependency(name) {
  return (
    packageJson.dependencies?.[name] ?? packageJson.devDependencies?.[name]
  );
}

function iosOutput(profile) {
  if (profile.ios?.simulator) return "Simulator app";
  return profile.distribution === "internal" ? "Ad-hoc IPA" : "App Store IPA";
}

function androidOutput(profile) {
  return profile.android?.buildType === "app-bundle" ? "Play AAB" : "APK";
}

const profileRows = Object.entries(eas.build ?? {})
  .map(([name, profile]) => {
    const distribution = profile.distribution ?? "store";
    return `- \`${name}\`: ${distribution} distribution; EAS environment \`${profile.environment ?? "—"}\`; Node \`${profile.node ?? "provider default"}\`; ${iosOutput(profile)} / ${androidOutput(profile)}.`;
  })
  .join("\n");

const rendered = `<!-- GENERATED by scripts/generate-runtime-doc.mjs from package.json, app.json, and eas.json. DO NOT EDIT. -->

# Mobile runtime and distribution configuration

This file is the generated, reviewable snapshot of the checked-in mobile manifests. It does not prove remote EAS versions, signing credentials, store state, or a successful device build.

## Runtime versions

- App / Expo app version: \`${packageJson.version}\` / \`${expo.version}\`.
- Expo SDK / Expo Router: \`${dependency("expo")}\` / \`${dependency("expo-router")}\`.
- React Native / React: \`${dependency("react-native")}\` / \`${dependency("react")}\`.
- NativeWind / TypeScript: \`${dependency("nativewind")}\` / \`${dependency("typescript")}\`.
- EAS CLI / app-version source: \`${eas.cli?.version}\` / \`${eas.cli?.appVersionSource}\`.
- Supported local Node versions: \`${packageJson.engines?.node}\`.

## Native identity

- iOS bundle / local build seed: \`${expo.ios?.bundleIdentifier}\` / \`${expo.ios?.buildNumber}\`.
- iPad support: \`${String(expo.ios?.supportsTablet)}\`.
- Android package / local version-code seed: \`${expo.android?.package}\` / \`${expo.android?.versionCode}\`.
- Orientation / URL scheme: \`${expo.orientation}\` / \`${expo.scheme}\`.

## EAS build profiles

${profileRows}

The checked-in development profile is simulator/emulator-only because its API and web origins are loopback. Physical-device development requires explicitly supplied HTTPS origins as documented in [README.md](./README.md#physical-device-development).
`;

if (process.argv.includes("--write")) {
  writeFileSync(outputPath, rendered);
  console.log(`[postwave-mobile] wrote ${outputPath}`);
  process.exit(0);
}

if (!process.argv.includes("--check")) {
  process.stdout.write(rendered);
  process.exit(0);
}

let current = "";
try {
  current = readFileSync(outputPath, "utf8");
} catch {
  // The mismatch message below is the actionable failure.
}
if (current !== rendered) {
  console.error(
    "[postwave-mobile] runtime-config.generated.md is stale; run pnpm --filter @postwave/mobile docs:runtime-generate and review the diff.",
  );
  process.exit(1);
}
console.log("[postwave-mobile] generated runtime documentation is current.");
