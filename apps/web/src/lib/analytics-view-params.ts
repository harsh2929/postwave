// URL state for the tenant Analytics page beyond ?range and ?tab (which the
// page itself owns). Pure — no React, no window access except through the
// arguments — so the deep-link contract is unit-testable and shared by every
// launcher (home tiles, the anomaly list, Copy link) and every reader.
//
//   ?metric=opens      focus one KPI (desktop parseAnalyticsHash `metric`)
//   ?focus=<chart-id>  scroll to + highlight one chart (desktop `focus`)
//   ?compare=off       hide the prior-period deltas (desktop `vsPrevious`)
//   ?group_by=campaign restore the grouped breakdown dimension
//
// Unknown values are ignored so an old or hand-typed link never breaks the
// page — it just opens unfocused.

import { normalizeRange } from "@/lib/analytics-format";

export const ANALYTICS_PATH = "/app/analytics";

/** KPIs the Analytics page can focus. */
export type FocusMetric =
  | "subscribers"
  | "opens"
  | "clicks"
  | "bounces"
  | "unsubscribes";

export const FOCUS_METRICS: readonly FocusMetric[] = [
  "subscribers",
  "opens",
  "clicks",
  "bounces",
  "unsubscribes",
];

const FOCUS_ALIASES: Record<string, FocusMetric> = {
  subs: "subscribers",
  subscriber: "subscribers",
  subscribers_total: "subscribers",
  open: "opens",
  open_rate: "opens",
  click: "clicks",
  click_rate: "clicks",
  bounce: "bounces",
  bounce_rate: "bounces",
  unsub: "unsubscribes",
  unsubs: "unsubscribes",
  unsubscribe: "unsubscribes",
  unsub_rate: "unsubscribes",
};

/**
 * Map a free-form metric name (a dashboard tile key, an anomaly row's metric,
 * a hand-typed link) onto a focusable KPI. Null when the page has no such KPI.
 */
export function asFocusMetric(
  value: string | null | undefined,
): FocusMetric | null {
  if (!value) return null;
  const key = value.trim().toLowerCase();
  if ((FOCUS_METRICS as readonly string[]).includes(key)) {
    return key as FocusMetric;
  }
  return FOCUS_ALIASES[key] ?? null;
}

/** Chart ids are generated by this app; anything else is ignored. */
const CHART_ID = /^[a-z][a-z0-9-]{0,63}$/;

export type GroupedDimension = "campaign" | "domain";

export interface AnalyticsView {
  metric: FocusMetric | null;
  focus: string | null;
  /** True unless the link explicitly turned the comparison off. */
  compare: boolean;
  groupBy: GroupedDimension | null;
  breakdownMetric?: "opens" | "clicks" | "bounces";
  breakdownDays?: 7 | 30 | 90;
}

export function parseAnalyticsView(search: string): AnalyticsView {
  const params = new URLSearchParams(search);
  const focus = params.get("focus");
  const groupBy = params.get("group_by");
  const breakdownMetric = params.get("breakdown_metric");
  const breakdownDays = Number(params.get("breakdown_days"));
  return {
    metric: asFocusMetric(params.get("metric")),
    focus: focus && CHART_ID.test(focus) ? focus : null,
    compare: params.get("compare") !== "off",
    groupBy: groupBy === "campaign" || groupBy === "domain" ? groupBy : null,
    ...(breakdownMetric === "opens" ||
    breakdownMetric === "clicks" ||
    breakdownMetric === "bounces"
      ? { breakdownMetric }
      : {}),
    ...(breakdownDays === 7 || breakdownDays === 30 || breakdownDays === 90
      ? { breakdownDays }
      : {}),
  };
}

/**
 * The in-app link that opens Analytics focused on one KPI over one window —
 * the web target for desktop's Dashboard StatGrid drill-down. The default
 * 30d window is omitted, matching how the page writes ?range itself.
 */
export function analyticsMetricHref(
  metric: FocusMetric,
  range?: string | null,
): string {
  const params = new URLSearchParams();
  const windowRange = normalizeRange(range);
  if (windowRange !== "30d") params.set("range", windowRange);
  params.set("metric", metric);
  return `${ANALYTICS_PATH}?${params.toString()}`;
}

/**
 * The absolute link a "Copy link" action puts on the clipboard: the current
 * Analytics view (range, tab, metric, compare…) with `focus` set to the chart
 * and any chart-specific params applied. Always the Analytics path, whatever
 * page the chart happens to be embedded in.
 */
export function buildAnalyticsChartLink(
  origin: string,
  currentSearch: string,
  chartId: string,
  extra: Record<string, string | null | undefined> = {},
): string {
  if (!CHART_ID.test(chartId)) {
    throw new Error("Chart links need a stable chart id.");
  }
  const params = new URLSearchParams(currentSearch);
  params.set("focus", chartId);
  for (const [key, value] of Object.entries(extra)) {
    if (value === null || value === undefined || value === "") {
      params.delete(key);
    } else {
      params.set(key, value);
    }
  }
  return `${origin}${ANALYTICS_PATH}?${params.toString()}`;
}

/**
 * The same URL with one param changed (null deletes it). Returns the
 * path+search+hash a caller hands to history.replaceState.
 */
export function withAnalyticsParam(
  href: string,
  key: string,
  value: string | null,
): string {
  const url = new URL(href);
  if (value === null) url.searchParams.delete(key);
  else url.searchParams.set(key, value);
  return `${url.pathname}${url.search}${url.hash}`;
}
