func env(values map[string]string) func(string) string {
	return func(key string) string { return values[key] }
}

// The extraction query must NEVER read the classifier's verdict.
//
// This is the property the whole tool exists to preserve, and it is asserted on
// the SQL rather than on an output row because that is where it can actually be
// lost. A corpus labelled from the classifier measures the classifier against
// itself: it reports perfect recall and perfect precision for ANY classifier,
// including a broken one, and the resulting Wilson bounds would be arithmetic
// wearing the costume of a measurement.
//
// A source assertion is normally a weak guard. Here it is the right one: the
// risk is that somebody ADDS the column back, and there is no runtime behaviour
// to observe because the correct behaviour is an absence.
func TestTheExtractionQueryNeverSelectsTheClassifierVerdict(t *testing.T) {
	source, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatalf("read main.go: %v", err)
	}
	body := string(source)
	queryStart := strings.Index(body, "SELECT o.id::text")
	if queryStart < 0 {
		t.Fatal("the extraction query was not found; this guard is pinned to it")
	}
	queryEnd := strings.Index(body[queryStart:], "LIMIT $4")
	if queryEnd < 0 {
		t.Fatal("the extraction query has no LIMIT; guard cannot bound its scan")
	}
	query := body[queryStart : queryStart+queryEnd]

	for _, forbidden := range []string{"classification", "o.classification", "classified"} {
		if strings.Contains(query, forbidden) {
			t.Fatalf("the extraction query reads %q; a corpus labelled from the "+
				"classifier measures the classifier against itself", forbidden)
		}
	}
	// Guard the guard: the slice must actually contain the query, or the check
	// above would pass on an empty string.
	if !strings.Contains(query, "subscriber_event_observations") {
		t.Fatalf("the extracted query text does not look like the query: %q", query)
	}
}

// controlled_machine must scope to seeds, in SQL.
//
// The label there is legitimate — a seed mailbox is one we own, so traffic to it
// is generated by construction — but ONLY for seeds. Scoping in Go after the
// fetch would still be correct; scoping in SQL means a non-seed row cannot be
// returned at all, so a later edit to the loop cannot widen it.
func TestControlledMachineExtractionIsScopedToSeedsInSQL(t *testing.T) {
	source, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatalf("read main.go: %v", err)
	}
	body := string(source)
	if !strings.Contains(body, `seedPredicate = " AND o.is_seed = true"`) {
		t.Fatal("controlled_machine no longer scopes to seeds in SQL")
	}
	if !strings.Contains(body, `seedPredicate = " AND o.is_seed = false"`) {
		t.Fatal("human corpora no longer EXCLUDE seeds; our own generated traffic " +
			"would be labelled as a person")
	}
	// And the belt-and-braces refusal after the fetch.
	if !strings.Contains(body, "controlled_machine extraction produced a non-seed row") {
		t.Fatal("the post-fetch seed refusal is gone")
	}
}

// Every required flag must be required, and the window must be explicit.
//
// A defaulted window would make the same command produce a different corpus
// tomorrow, and a corpus whose contents depend on WHEN it was extracted cannot
// be re-derived by whoever later audits the bounds it produced.
func TestExtractionRefusesAnIncompleteInvocation(t *testing.T) {
	base := []string{
		"--tenant", "00000000-0000-4000-8000-000000000001",
		"--since", "2026-01-01T00:00:00Z", "--until", "2026-02-01T00:00:00Z",
		"--out", t.TempDir(), "--name", "c1",
	}
	getenv := env(map[string]string{"DATABASE_URL": "postgres://ignored/db"})

	for _, tc := range []struct{ name, drop string }{
		{"no tenant", "--tenant"},
		{"no window start", "--since"},
		{"no window end", "--until"},
		{"no output directory", "--out"},
		{"no name", "--name"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			args := make([]string, 0, len(base))
			for i := 0; i < len(base); i += 2 {
				if base[i] == tc.drop {
					continue
				}
				args = append(args, base[i], base[i+1])
			}
			if _, err := parseOptions(args, getenv, &bytes.Buffer{}); err == nil {
				t.Fatalf("an invocation missing %s was accepted", tc.drop)
			}
		})
	}

	// Guard the guard: the complete invocation must parse, or every assertion
	// above would pass against a parser that rejected everything.
	if _, err := parseOptions(base, getenv, &bytes.Buffer{}); err != nil {
		t.Fatalf("a complete invocation was refused: %v", err)
	}

	// An inverted window is refused rather than silently returning nothing.
	inverted := append([]string(nil), base...)
	for i := range inverted {
		if inverted[i] == "2026-02-01T00:00:00Z" {
			inverted[i] = "2025-01-01T00:00:00Z"
		}
	}
	if _, err := parseOptions(inverted, getenv, &bytes.Buffer{}); err == nil {
		t.Fatal("a window ending before it starts was accepted")
	}
}

// The written manifest must describe the file that was actually written.
//
// The loader verifies examples_sha256, so a manifest whose digest does not match
// its own examples file is a directory that can never be loaded — a failure a
// reviewer would meet only after doing all the labelling work.
func TestTheWrittenManifestMatchesItsExamplesFile(t *testing.T) {
	dir := t.TempDir()
	opts := options{outputDir: dir, name: "c1", version: "v1", kind: "labeled_human"}
	examples := []candidate{
		{ID: "1", SamplingUnitHash: "h1", Source: "listmonk", EventType: "opened"},
		{ID: "2", SamplingUnitHash: "h2", Source: "listmonk", EventType: "clicked"},
	}
	if _, err := write(opts, examples); err != nil {
		t.Fatalf("write: %v", err)
	}
	manifestBody, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		t.Fatalf("read manifest: %v", err)
	}
	examplesBody, err := os.ReadFile(filepath.Join(dir, "examples.json"))
	if err != nil {
		t.Fatalf("read examples: %v", err)
	}
	if !strings.Contains(string(manifestBody), `"sample_count": 2`) {
		t.Fatalf("manifest does not state the sample count: %s", manifestBody)
	}
	// The examples must carry NO ground truth for a human corpus.
	if strings.Contains(string(examplesBody), `"ground_truth":"human"`) ||
		strings.Contains(string(examplesBody), `"ground_truth":"machine"`) {
		t.Fatalf("an unlabelled extraction emitted a ground truth: %s", examplesBody)
	}
	if !strings.Contains(string(examplesBody), `"ground_truth":""`) {
		t.Fatalf("examples do not carry an explicit empty ground truth: %s", examplesBody)
	}
}

// The extractor's output must LOAD. This is a contract test between two
// packages that would otherwise drift silently.
//
// It earns its place: writing it caught three separate defects in this tool that
// every unit test above had missed — a contract_version string with one word
// wrong, a JSON array where the loader reads NDJSON, and guidance that told a
// reviewer to label each row when the corpus kinds are single-class. Each would
// have been discovered by a human only AFTER labelling a whole file.
//
// The labelling step here stands in for the reviewer. It is not a claim that
// these rows are human traffic — it is the mechanical step whose FORMAT is under
// test.
func TestExtractedCandidatesLoadAsACorpusOnceLabelled(t *testing.T) {
	dir := t.TempDir()
	opts := options{
		outputDir: dir, name: "round-trip", version: "v1", kind: "labeled_human",
	}
	examples := []candidate{
		{
			ID: "11111111-1111-4111-8111-111111111111", SamplingUnitHash: strings.Repeat("a", 64),
			Source: "listmonk", EventType: "opened", OccurredAt: time.Unix(1767225600, 0).UTC(),
		},
		{
			ID: "22222222-2222-4222-8222-222222222222", SamplingUnitHash: strings.Repeat("b", 64),
			Source: "listmonk", EventType: "clicked", OccurredAt: time.Unix(1767225601, 0).UTC(),
		},
	}
	if _, err := write(opts, examples); err != nil {
		t.Fatalf("write: %v", err)
	}

	// The reviewer's step, mechanically: every retained line gets the corpus's
	// single class.
	raw, err := os.ReadFile(filepath.Join(dir, "examples.json"))
	if err != nil {
		t.Fatalf("read examples: %v", err)
	}
	labelled := strings.ReplaceAll(string(raw), `"ground_truth":""`, `"ground_truth":"human"`)
	if labelled == string(raw) {
		t.Fatalf("no unlabelled ground_truth found to label; the writer's shape changed: %s", raw)
	}
	if err := os.WriteFile(filepath.Join(dir, "examples.json"), []byte(labelled), 0o644); err != nil {
		t.Fatalf("write labelled: %v", err)
	}
	sum := sha256.Sum256([]byte(labelled))
	manifestRaw, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		t.Fatalf("read manifest: %v", err)
	}
	var m manifest
	if err := json.Unmarshal(manifestRaw, &m); err != nil {
		t.Fatalf("decode manifest: %v", err)
	}
	m.ExamplesSHA256 = hex.EncodeToString(sum[:])
	updated, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		t.Fatalf("encode manifest: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "manifest.json"), append(updated, '\n'), 0o644); err != nil {
		t.Fatalf("write manifest: %v", err)
	}

	corpus, err := engagementclassification.LoadCalibrationCorpusDirectory(dir)
	if err != nil {
		t.Fatalf("the extractor produced a directory the corpus loader refuses: %v", err)
	}
	loaded := 0
	if err := corpus.ForEach(context.Background(),
		func(engagementclassification.LabeledExample) error { loaded++; return nil }); err != nil {
		t.Fatalf("ForEach: %v", err)
	}
	if loaded != len(examples) {
		t.Fatalf("loaded %d examples, wrote %d", loaded, len(examples))
	}
}
