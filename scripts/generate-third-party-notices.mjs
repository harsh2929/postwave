#!/usr/bin/env node
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const policy = JSON.parse(
  readFileSync(path.join(root, "config/license-policy.json"), "utf8"),
);
const checkOnly = process.argv.includes("--check");
const outputFlag = process.argv.indexOf("--output");
const outputPath = path.resolve(
  root,
  outputFlag >= 0
    ? (process.argv[outputFlag + 1] ?? fail("--output requires a path"))
    : "artifacts/THIRD_PARTY_NOTICES.md",
);

const result = spawnSync("pnpm", ["licenses", "list", "--json", "--prod"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
if (result.status !== 0) {
  process.stderr.write(result.stderr);
  fail("pnpm license inventory failed");
}

let inventory;
try {
  inventory = JSON.parse(result.stdout);
} catch (error) {
  fail(`pnpm returned invalid license JSON: ${error.message}`);
}

const rows = [];
for (const [groupLicense, packages] of Object.entries(inventory)) {
  for (const pkg of packages) {
    if (isPostwavePackage(pkg.name)) continue;
    const license = String(pkg.license || groupLicense || "Unknown");
    for (const version of pkg.versions ?? []) {
      rows.push({
        name: String(pkg.name),
        version: String(version),
        license,
        homepage: String(pkg.homepage || ""),
      });
    }
  }
}

rows.sort((a, b) =>
  a.name.localeCompare(b.name) ||
  a.version.localeCompare(b.version) ||
  a.license.localeCompare(b.license),
);

const violations = [];
const today = new Date().toISOString().slice(0, 10);
for (const exception of policy.exceptions ?? []) {
  if (exception.expires_on < today) {
    violations.push(
      `license exception ${exception.package_pattern} expired on ${exception.expires_on}`,
    );
  }
}

for (const row of rows) {
  if (!requiresReview(row.license)) continue;
  const exception = (policy.exceptions ?? []).find(
    (item) =>
      new RegExp(item.package_pattern, "u").test(row.name) &&
      item.licenses.includes(row.license) &&
      item.versions.includes(row.version),
  );
  if (!exception) {
    violations.push(
      `${row.name}@${row.version} uses review-required license '${row.license}' without a current exception`,
    );
  }
}

if (violations.length > 0) {
  console.error("Third-party license policy failed:");
  for (const violation of violations) console.error(`- ${violation}`);
  process.exit(1);
}

if (checkOnly) {
  console.log(
    `Third-party license policy passed for ${rows.length} resolved production npm package versions (${process.platform}/${process.arch}).`,
  );
  process.exit(0);
}

const lockDigest = createHash("sha256")
  .update(readFileSync(path.join(root, "pnpm-lock.yaml")))
  .digest("hex");
const lines = [
  "# Third-Party Notices — resolved production npm graph",
  "",
  "> Generated by `scripts/generate-third-party-notices.mjs`; do not hand edit.",
  `> Platform: \`${process.platform}/${process.arch}\`. pnpm lock SHA-256: \`${lockDigest}\`.`,
  "> This inventory accompanies, but does not replace, license texts and notices embedded by upstream packages or the SPDX SBOM attached to release artifacts.",
  "",
  "| Package | Version | Declared license | Upstream |",
  "| --- | --- | --- | --- |",
  ...rows.map(
    (row) =>
      `| ${escapeCell(row.name)} | ${escapeCell(row.version)} | ${escapeCell(row.license)} | ${row.homepage ? `[link](${row.homepage})` : "—"} |`,
  ),
  "",
  `Resolved package versions: **${rows.length}**.`,
  "",
];

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log(`Wrote ${path.relative(root, outputPath)} (${rows.length} rows).`);

function requiresReview(license) {
  if ((policy.review_required_licenses ?? []).includes(license)) return true;
  const alternatives = license.split(/\s+OR\s+/iu);
  if (alternatives.length > 1) {
    return alternatives.every((part) => /(?:^|[^A-Z])A?GPL/iu.test(part));
  }
  return /(?:^|[^A-Z])A?GPL/iu.test(license) && !/^MPL/iu.test(license);
}

function isPostwavePackage(name) {
  return (
    name.startsWith("@postwave/") ||
    name === "postwave-desktop-shell" ||
    name === "postwave-zapier"
  );
}

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
